async function obtenerImagen(receta: RecetaSeed): Promise<{
  imagenUrl: string;
  fotoFuente: "usuario" | "pexels";
  fotoCredito: { fotografo: string; urlFoto: string; urlPerfil: string } | null;
}> {
  if (SIN_IMAGENES || pexelsUsadas >= PEXELS_BUDGET) {
    return { imagenUrl: placeholder(receta.titulo), fotoFuente: "usuario", fotoCredito: null };
  }
  pexelsUsadas++;
  const foto = await buscarFotoPexelsCascada(receta.titulo, receta.categorias);
  await sleep(PEXELS_SLEEP_MS);
  if (!foto) {
    return { imagenUrl: placeholder(receta.titulo), fotoFuente: "usuario", fotoCredito: null };
  }
  return {
    imagenUrl: foto.url,
    fotoFuente: "pexels",
    fotoCredito: { fotografo: foto.fotografo, urlFoto: foto.urlFoto, urlPerfil: foto.urlPerfil },
  };
}

function randomInt(min: number, max: number): number {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

async function run(): Promise<void> {
  await conectarDB();

  console.log("👤 Asegurando usuarios...");
  const usuarios = await Promise.all(
    USUARIOS.map(async (u) => {
      const existente = await Usuario.findOne({ correo: u.correo });
      if (existente) return existente;
      const hash = await bcrypt.hash(PASSWORD_SEED, 10);
      return Usuario.create({
        nombre: u.nombre,
        correo: u.correo,
        contrasena: hash,
        foto: avatar(u.nombre),
        rol: "usuario",
        proveedor: "local",
        cuentaVerificada: true,
        perfilCompleto: true,
        alergias: u.alergias,
        preferencias: u.preferencias,
      });
    }),
  );
  console.log(`   ✅ ${usuarios.length} usuarios listos`);

  console.log(`\n🍳 Insertando recetas (${RECETAS.length})${SIN_IMAGENES ? " sin imágenes" : " con fotos de Pexels"}...`);
  const idsRecetasNuevas: mongoose.Types.ObjectId[] = [];
  let creadas = 0;
  let saltadas = 0;

  for (const receta of RECETAS) {
    const autor = usuarios[receta.autorIndex];
    const yaExiste = await Receta.findOne({ titulo: receta.titulo, autorId: autor._id });
    if (yaExiste) {
      saltadas++;
      continue;
    }

    const imagen = await obtenerImagen(receta);

    const doc = await Receta.create({
      autorId: autor._id,
      titulo: receta.titulo,
      descripcion: receta.descripcion,
      imagenUrl: imagen.imagenUrl,
      fotoFuente: imagen.fotoFuente,
      fotoCredito: imagen.fotoCredito,
      tiempo: receta.tiempo,
      dificultad: receta.dificultad,
      porciones: receta.porciones,
      categorias: receta.categorias,
      ingredientes: receta.ingredientes,
      pasos: receta.pasos,
      alergenos: receta.alergenos,
      macros: receta.macros,
      esEvento: receta.esEvento ?? false,
      likes: [],
      listaComentarios: (receta.comentarios ?? []).map((c) => ({
        autorId: usuarios[c.autorIndex]._id,
        autorNombre: usuarios[c.autorIndex].nombre,
        avatarUrl: usuarios[c.autorIndex].foto ?? null,
        texto: c.texto,
        fecha: new Date(),
      })),
      fechaPublicacion: new Date(Date.now() - randomInt(0, 90) * 24 * 60 * 60 * 1000),
    });

    idsRecetasNuevas.push(doc._id as mongoose.Types.ObjectId);
    creadas++;
    process.stdout.write(`  · ${receta.titulo} ${imagen.fotoFuente === "pexels" ? "📷" : "▫"}\n`);
  }

  console.log(`\n   ✅ ${creadas} recetas nuevas · ${saltadas} ya existían`);

  console.log("\n❤️  Repartiendo likes...");
  const todosLosIds = usuarios.map((u) => u._id);
  for (const recetaId of idsRecetasNuevas) {
    const nLikes = randomInt(0, usuarios.length);
    const mezclados = [...todosLosIds].sort(() => Math.random() - 0.5).slice(0, nLikes);
    if (mezclados.length > 0) {
      await Receta.updateOne({ _id: recetaId }, { $addToSet: { likes: { $each: mezclados } } });
    }
  }

  console.log("\n👥 Creando relaciones de seguimiento...");
  for (let i = 0; i < usuarios.length; i++) {
    const seguidos = [...usuarios]
      .filter((_, idx) => idx !== i)
      .sort(() => Math.random() - 0.5)
      .slice(0, randomInt(2, 5))
      .map((u) => u._id);
    await Usuario.findByIdAndUpdate(usuarios[i]._id, { $addToSet: { seguidos: { $each: seguidos } } });
    await Promise.all(
      seguidos.map((sid) =>
        Usuario.findByIdAndUpdate(sid, { $addToSet: { seguidores: usuarios[i]._id } }),
      ),
    );
  }

  console.log("\n🎉 Seed masivo completado:");
  console.log(`   Usuarios : ${usuarios.length}`);
  console.log(`   Recetas  : ${creadas} nuevas`);
  console.log(`\n🔑 Contraseña de todos los chefs seed: ${PASSWORD_SEED}`);

  await mongoose.disconnect();
}

run().catch((err) => {
  console.error("❌ Error en el seed masivo:", err);
  process.exit(1);
});
